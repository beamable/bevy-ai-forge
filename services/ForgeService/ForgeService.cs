        public async Promise<FederatedInventoryProxyState> StartInventoryTransaction(string id, string transaction, Dictionary<string, long> currencies, List<FederatedItemCreateRequest> newItems, List<FederatedItemDeleteRequest> deleteItems,
            List<FederatedItemUpdateRequest> updateItems)
        {
            var stopWatch = Stopwatch.StartNew();
            var db = await Storage.ForgeStorageDatabase();
            var contentApi = Provider.GetService<AiContentService>();
            var ledger = new InventoryTransactionLedger
            {
                PlayerId = id,
                TransactionId = transaction,
            };
            var placeholders = new List<AiInventoryItem>();
            for (var index = 0; index < newItems.Count; index++)
            {
                var request = newItems[index];
                if (!contentApi.TryGetContent(request.contentId, out _))
                {
                    BeamableLogger.LogWarning("Ignoring unsupported inventory content {ContentId}", request.contentId);
                    continue;
                }
                var forgedTimes = request.properties != null
                    && request.properties.TryGetValue("forgedTimes", out var value)
                    && long.TryParse(value, out var parsed)
                        ? parsed
                        : 0;
                var itemId = DeterministicItemId(id, transaction, index, request.contentId);
                var properties = request.properties == null
                    ? new Dictionary<string, string>()
                    : new Dictionary<string, string>(request.properties);
                properties["forgeStatus"] = "processing";
                placeholders.Add(new AiInventoryItem
                {
                    ItemId = itemId,
                    GamerTag = id,
                    ContentId = request.contentId,
                    Properties = properties,
                });
                ledger.Items.Add(new InventoryTransactionItem
                {
                    ItemId = itemId,
                    ContentId = request.contentId,
                    ForgedTimes = forgedTimes,
                });
            }

            var deleteIds = deleteItems.Select(item => item.proxyId).ToArray();
            var claim = await InventoryTransactionLedgerCollection.ClaimAndApply(
                db, ledger, placeholders, deleteIds);

            foreach (var item in claim.Ledger.Items)
            {
                await Services.Scheduler.Schedule().Microservice<ForgeService>()
                    .Run(service => service.RebuildItem, item.ItemId, item.ForgedTimes)
                    .After(TimeSpan.FromSeconds(1))
                    .Save($"enrich-item-{item.ItemId}");

                if (claim.Claimed && contentApi.TryGetContent(item.ContentId, out var content))
                {
                    await TryBumpStat(SignedRequester, Context.UserId, content.StatKey(), 1);
                }
            }

            var current = await AiInventoryItemCollection.GetAll(db, id);
            BeamableLogger.Log(
                "Inventory transaction accepted in {Duration}ms (creates {Creates}, deletes {Deletes}, replay {Replay})",
                stopWatch.ElapsedMilliseconds,
                claim.Ledger.Items.Count,
                deleteIds.Length,
                !claim.Claimed);
            return current.ToFederatedInventoryProxyState();
        }

        private static string DeterministicItemId(string playerId, string transaction, int index, string contentId)
        {
            var bytes = SHA256.HashData(Encoding.UTF8.GetBytes($"{playerId}:{transaction}:{index}:{contentId}"));
            return Convert.ToHexString(bytes).ToLowerInvariant()[..32];
        }


